import type { LiveSalesCallValues } from "./live-sales-call";

export type TalentFacts = {
  companyName?: string | null;
  clientName?: string | null;
  role?: string | null;
  headcount?: number | string | null;
  responsibilities?: string | null;
  skills?: string | null;
  schedule?: string | null;
  timezone?: string | null;
  budget?: string | null;
  experience?: string | null;
  special?: string | null;
  startDate?: string | null;
  interviewAvailability?: string | null;
  meetingNotes?: string | null;
};

const SALES_CALL_TASK_DUMP = [
  "Review and Approve Meeting Notes",
  "Send Talent Request to Recruitment",
];

const LABELS: Array<[keyof TalentFacts, string]> = [
  ["companyName", "Client / company"],
  ["clientName", "Client contact"],
  ["role", "VA role"],
  ["headcount", "Number of VAs"],
  ["responsibilities", "Responsibilities"],
  ["skills", "Required skills"],
  ["schedule", "Work schedule"],
  ["timezone", "Time zone"],
  ["budget", "Budget or approved rate"],
  ["experience", "Preferred experience"],
  ["special", "Special requirements"],
  ["startDate", "Target start date"],
  ["interviewAvailability", "Candidate Interview Availability"],
  ["meetingNotes", "Sales call meeting notes"],
];

const STRUCTURED_LINES: Array<[keyof TalentFacts, string]> = LABELS.filter(([key]) => key !== "meetingNotes");

function present(value: string | number | null | undefined) {
  if (value == null) return false;
  if (typeof value === "number") return Number.isFinite(value);
  return value.trim().length > 0;
}

export function isSalesCallTaskDump(value: string | null | undefined) {
  const text = String(value ?? "");
  return SALES_CALL_TASK_DUMP.every((title) => text.includes(title));
}

export function usableResponsibilities(value: string | null | undefined) {
  if (!present(value) || isSalesCallTaskDump(value)) return null;
  return String(value).trim();
}

export function isAutoGeneratedTalentDraft(body: string | null | undefined) {
  const text = String(body ?? "");
  return (
    /This draft uses only information already saved in SalesApp/i.test(text) ||
    /based on the sales call meeting notes/i.test(text)
  );
}

export function missingTalentFields(facts: TalentFacts) {
  return LABELS.filter(([key]) => !present(facts[key])).map(([, label]) => label);
}

export function talentFactsFromLiveCall(
  values: LiveSalesCallValues,
  input: { companyName?: string | null; clientName?: string | null; extraNotes?: string | null },
): TalentFacts {
  const notes = values.notes.trim() || input.extraNotes?.trim() || null;
  return {
    companyName: input.companyName,
    clientName: input.clientName,
    role: values.role.trim() || null,
    headcount: values.headcount.trim() || null,
    responsibilities: usableResponsibilities(values.responsibilities),
    skills: values.skills.trim() || null,
    schedule: values.schedule.trim() || null,
    timezone: values.timezone.trim() || null,
    budget: values.billingRate.trim() || values.budget.trim() || null,
    experience: values.experience.trim() || null,
    special: values.special.trim() || values.dealBreakers.trim() || null,
    startDate: values.startDate.trim() || null,
    interviewAvailability: values.interviewAvailability.trim() || null,
    meetingNotes: notes,
  };
}

export function buildTalentRequestEmail(facts: TalentFacts) {
  const cleaned: TalentFacts = {
    ...facts,
    responsibilities: usableResponsibilities(facts.responsibilities),
  };
  const missing = missingTalentFields(cleaned);
  const company = cleaned.companyName?.toString().trim() || "the client";
  const contact = cleaned.clientName?.toString().trim();
  const notes = cleaned.meetingNotes?.toString().trim();
  const structured = STRUCTURED_LINES.filter(([key]) => present(cleaned[key])).map(
    ([key, label]) => `${label}: ${cleaned[key]}`,
  );
  const body = [
    "Hi Recruitment,",
    "",
    contact
      ? `Please help us source candidates for ${company} based on the sales call meeting notes with ${contact}.`
      : `Please help us source candidates for ${company} based on the sales call meeting notes saved in SalesApp.`,
    "",
    "Sales call meeting notes:",
    notes || "[Not in SalesApp yet]",
    "",
    ...structured,
    "",
    missing.length > 0
      ? `Still needed before this is complete:\n${missing.map((item) => `- ${item}`).join("\n")}`
      : "All listed fields were present in SalesApp.",
    "",
    "Thank you,",
    "Sales",
  ].join("\n");
  return { body, missing };
}
