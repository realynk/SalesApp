import assert from "node:assert/strict";
import test from "node:test";
import { emptyLiveSalesCallValues } from "./live-sales-call.ts";
import {
  buildTalentRequestEmail,
  isAutoGeneratedTalentDraft,
  isSalesCallTaskDump,
  missingTalentFields,
  talentFactsFromLiveCall,
  usableResponsibilities,
} from "./talent-request.ts";

test("talent request does not invent missing client details", () => {
  const drafted = buildTalentRequestEmail({
    companyName: "Harbor & Co.",
    clientName: "Priya Shah",
    headcount: 2,
  });
  assert.match(drafted.body, /Harbor & Co\./);
  assert.match(drafted.body, /Priya Shah/);
  assert.match(drafted.body, /Number of VAs: 2/);
  assert.match(drafted.body, /Sales call meeting notes:\n\[Not in SalesApp yet\]/);
  assert.doesNotMatch(drafted.body, /VA role: \[Not in SalesApp yet\]/);
  assert.ok(drafted.missing.includes("VA role"));
  assert.ok(drafted.missing.includes("Candidate Interview Availability"));
  assert.ok(drafted.missing.includes("Sales call meeting notes"));
  assert.equal(missingTalentFields({ companyName: "Harbor & Co." }).includes("Client / company"), false);
});

test("complete facts produce no missing list items in the checklist", () => {
  const drafted = buildTalentRequestEmail({
    companyName: "Acme",
    clientName: "Pat",
    role: "EA",
    headcount: 1,
    responsibilities: "Inbox",
    skills: "Calendar",
    schedule: "9-5",
    timezone: "ET",
    budget: "1500",
    experience: "2 years",
    special: "NDA",
    startDate: "2026-11-01",
    interviewAvailability: "Tue/Thu 2-4pm America/New_York",
    meetingNotes: "Needs inbox coverage and calendar support.",
  });
  assert.deepEqual(drafted.missing, []);
  assert.doesNotMatch(drafted.body, /\[Not in SalesApp yet\]/);
  assert.match(drafted.body, /Sales call meeting notes:\nNeeds inbox coverage and calendar support\./);
  assert.match(drafted.body, /Candidate Interview Availability: Tue\/Thu 2-4pm America\/New_York/);
  assert.doesNotMatch(drafted.body, /Interview Preference/);
});

test("automation task titles are not treated as job responsibilities", () => {
  const dump = "Review and Approve Meeting Notes\nSend Talent Request to Recruitment";
  assert.equal(isSalesCallTaskDump(dump), true);
  assert.equal(usableResponsibilities(dump), null);
  const drafted = buildTalentRequestEmail({
    companyName: "Eden Capital Careers",
    clientName: "Xavier Brockman",
    responsibilities: dump,
    meetingNotes: "Part-time SDR to book meetings with school districts.",
  });
  assert.doesNotMatch(drafted.body, /Responsibilities: Review and Approve Meeting Notes/);
  assert.match(drafted.body, /Part-time SDR to book meetings with school districts/);
});

test("live call notes drive the recruitment email", () => {
  const values = emptyLiveSalesCallValues();
  values.role = "SDR";
  values.notes = "Outbound calling to hospitals. Client will provide lists.";
  values.interviewAvailability = "Thu 3pm ET";
  const facts = talentFactsFromLiveCall(values, {
    companyName: "Eden Capital Careers",
    clientName: "Xavier Brockman",
  });
  const drafted = buildTalentRequestEmail(facts);
  assert.match(drafted.body, /based on the sales call meeting notes with Xavier Brockman/);
  assert.match(drafted.body, /Outbound calling to hospitals/);
  assert.match(drafted.body, /VA role: SDR/);
  assert.equal(isAutoGeneratedTalentDraft(drafted.body), true);
});
